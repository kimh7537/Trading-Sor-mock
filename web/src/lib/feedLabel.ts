import type { FeedStatus } from "./types";

/**
 * "지금 호가를 **무엇이** 만들고 있나"를 한 곳에서 적는다 (점검).
 *
 * 예전에는 배지가 "시뮬"이라고만 적었다. 그런데 `ledgerd --live`로 띄우면 가상 참가자가
 * 초당 수십 건을 내 호가창이 활발히 움직이고, 그것을 본 사람은 **실시세라고 오해한다** —
 * 실제로 그랬다. "시뮬"은 *무엇이 아닌지*만 말할 뿐 *무엇인지*는 말하지 않는다.
 *
 * 그래서 세 가지를 구분해 적고, 화면 어디서든 같은 말을 쓴다. 네 군데가 각자 문구를
 * 적고 있었고 그래서 말이 조금씩 달랐다.
 *
 * | 상태 | 호가를 만드는 것 |
 * |---|---|
 * | 실시세 | 바깥 시장에서 받은 실호가 |
 * | 시뮬 · 가상 참가자 켜짐 | 이 프로젝트가 지어낸 호가. **움직여도 실시세가 아니다** |
 * | 시뮬 · 가상 참가자 꺼짐 | 아무도 없다. 호가창이 그 자리에 선다 |
 */
export interface FeedLabel {
  /** 맨 위 배지. 자리가 좁으므로 짧게 */
  badge: string;
  /** 패널 제목 옆 한 줄 */
  sub: string;
  /** 마우스를 올렸을 때, 또는 설명 문단에 쓰는 긴 문장 */
  long: string;
  /** 호가가 지어낸 값인가. 참이면 화면이 그것을 눈에 띄게 적는다 */
  synthetic: boolean;
}

export function feedLabel(feed: FeedStatus | null): FeedLabel {
  if (!feed) {
    return {
      badge: "시세 모드 확인 중",
      sub: "시세 모드를 읽는 중",
      long: "채널계에서 시세 모드를 읽는 중이다.",
      synthetic: false,
    };
  }
  if (feed.mode === "live") {
    return {
      badge: "실시세 · 주문은 모의",
      sub: "바깥에서 받은 실호가",
      long:
        "호가는 바깥 시장에서 받아 온 실제 값이다. 주문·체결·잔고는 전부 이 프로젝트의 원장 안에서만 일어난다 — 바깥으로 주문이 나가지 않는다.",
      synthetic: false,
    };
  }
  if (feed.simTicks) {
    return {
      badge: "시뮬 · 가상 참가자가 호가를 만든다",
      sub: "가상 참가자가 만든 호가 — 실시세가 아니다",
      long:
        "호가를 움직이는 것은 이 프로젝트의 가상 참가자다. 바깥 시세와 아무 관계가 없으므로, 활발히 움직여도 실시세가 아니다.",
      synthetic: true,
    };
  }
  return {
    badge: "시뮬 · 호가 정지",
    sub: "가상 참가자가 꺼져 있다 — 호가가 움직이지 않는다",
    long:
      "원장을 --live 없이 띄웠다. 처음 넣은 시드 유동성만 있고 아무도 새 호가를 내지 않아 호가창이 그 자리에 서 있다.",
    synthetic: true,
  };
}
