#ifndef MINI_SOR_SNAPSHOT_H
#define MINI_SOR_SNAPSHOT_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "journal.h"

/*
 * 스냅샷과 재기동 복구.
 *
 * ===========================================================================
 * 스냅샷은 저널을 대신하지 않는다
 * ===========================================================================
 *
 * 저널(T5-01)만으로도 되살릴 수 있다. 처음부터 다 재생하면 된다. 스냅샷은
 * **그 시간을 줄이는 것**이지 진실을 옮겨 오는 것이 아니다.
 *
 * 이 구분이 중요한 이유: 스냅샷이 깨졌을 때 무엇을 할지가 여기서 정해진다.
 * 스냅샷이 진실이었다면 깨진 순간 복구가 불가능하다. 저널이 진실이므로
 * **깨진 스냅샷은 그냥 버리고 처음부터 재생하면 된다.** 느릴 뿐 틀리지 않는다.
 *
 * ===========================================================================
 * 어디까지 담았는지를 반드시 함께 적는다
 * ===========================================================================
 *
 * 스냅샷은 "저널의 N번까지 반영한 상태"다. **N을 모르면 쓸 수 없다.**
 *
 *  - 처음부터 재생하면 이미 반영된 것을 **두 번 반영한다** — 체결이 두 배가
 *    되고, 그 틀림은 장이 끝난 뒤 잔고가 안 맞을 때에야 드러난다
 *  - 아무것도 재생하지 않으면 스냅샷 이후의 주문이 통째로 사라진다
 *
 * 그래서 `upto_seq`가 스냅샷의 일부다. 옵션이 아니다.
 *
 * ===========================================================================
 * 쓰기는 원자적이어야 한다 — 임시 파일에 쓰고 이름을 바꾼다
 * ===========================================================================
 *
 * 스냅샷 파일에 바로 쓰다 죽으면 **반쪽 스냅샷이 원래 자리에 남는다.**
 * 다음 재기동은 그것을 읽고 시작하고, 그 시스템은 **조용히 틀린 상태로 돈다.**
 * 저널처럼 "찢어진 꼬리를 버리는" 방식이 통하지 않는다 — 스냅샷은 통째로
 * 하나의 상태이지 이어 붙인 기록이 아니기 때문이다.
 *
 * 그래서 **임시 파일에 다 쓰고 `fsync`한 뒤 `rename`한다.** POSIX에서 같은
 * 파일 시스템 안의 `rename`은 원자적이다 — 어느 시점에 죽어도 원래 파일은
 * 옛 스냅샷이거나 새 스냅샷이지, 반쪽인 적이 없다.
 *
 * CRC도 둔다. `rename`이 원자적이어도 디스크가 나중에 썩을 수 있다.
 */

/* "MSS1" */
#define SNAPSHOT_MAGIC 0x4D535331u

/* 스냅샷 본문 상한. */
#define SNAPSHOT_MAX 1048576u

/* magic(4) len(4) upto_seq(8) */
#define SNAPSHOT_HEADER_LEN 16u

/*
 * 상태를 파일로 남긴다. `upto_seq`는 **저널의 어디까지를 담았는지**다.
 *
 * 임시 파일에 쓰고 이름을 바꾼다. 성공하면 ERR_OK.
 */
int snapshot_write(const char *path, uint64_t upto_seq, const uint8_t *data,
                   uint32_t len);

/*
 * 스냅샷을 읽는다. 성공하면 본문 길이, `*out_seq`에 담긴 지점.
 *
 * 파일이 없으면 ERR_NOT_FOUND. 깨졌으면 ERR_IO —
 * **부르는 쪽은 둘을 같게 다뤄도 된다.** 둘 다 "스냅샷 없이 시작한다"는 뜻이다.
 */
int snapshot_read(const char *path, uint64_t *out_seq, uint8_t *out,
                  uint32_t cap);

/* 복구할 때 상태를 되살리는 쪽에 넘기는 모양. */
typedef struct {
    /* 스냅샷 본문을 상태에 밀어 넣는다. 스냅샷이 없으면 불리지 않는다. */
    int (*load)(const uint8_t *data, uint32_t len, void *ctx);
    /* 저널 레코드 하나를 상태에 반영한다. */
    int (*apply)(const jrec_t *rec, void *ctx);
    void *ctx;
} snap_apply_fn;

/* 복구 결과. 무엇이 일어났는지 숨기지 않는다. */
typedef struct {
    bool     used_snapshot;
    bool     snapshot_bad; /* 있었지만 못 썼다 */
    uint64_t from_seq;     /* 이 번호 다음부터 재생했다 */
    int      replayed;     /* 반영한 저널 레코드 수 */
    bool     journal_torn; /* 저널 꼬리가 찢어져 있었다 */
} recover_result_t;

/*
 * 스냅샷 + 그 이후 저널로 상태를 되살린다.
 *
 * 스냅샷이 없거나 깨졌으면 **저널만으로** 되살린다(느릴 뿐 틀리지 않는다).
 * 성공하면 ERR_OK. `out`은 무슨 일이 있었는지를 담는다 — 조용히 넘어가면
 * "스냅샷을 썼다"와 "못 써서 처음부터 했다"가 구분되지 않는다.
 */
int recover(const char *snapshot_path, const char *journal_path,
            const snap_apply_fn *fns, recover_result_t *out);

#endif /* MINI_SOR_SNAPSHOT_H */
