#ifndef MINI_SOR_JOURNAL_H
#define MINI_SOR_JOURNAL_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/*
 * 저널 — 덧붙이기만 하는 입력 기록.
 *
 * ===========================================================================
 * 입력을 적는다. 결과는 적지 않는다
 * ===========================================================================
 *
 * 매칭 엔진과 SOR 엔진은 **결정적**이다(CLAUDE.md). 같은 입력 시퀀스는 항상
 * 같은 출력을 만든다. 그러면 **입력만 있으면 결과를 다시 만들 수 있다.**
 *
 * 결과까지 적으면 두 가지를 잃는다.
 *
 *  1. **양이 몇 배로 는다.** 주문 하나가 체결 수십 건을 낳는다
 *  2. **진실이 둘이 된다.** 적어 둔 결과와 다시 계산한 결과가 어긋나면
 *     어느 쪽이 맞는가? 답할 방법이 없다
 *
 * 그래서 입력만 적는다. **결정성이 이 선택을 가능하게 한다** — 결정적이지
 * 않았다면 입력만으로는 아무것도 되살릴 수 없다.
 *
 * ===========================================================================
 * 여기서는 검사값을 둔다 (T3-01과 반대다)
 * ===========================================================================
 *
 * 전문(T3-01)에는 체크섬을 넣지 않았다. TCP가 이미 하고 있고, 같은 검사를 두
 * 겹 두면 한쪽만 고치는 일이 생기기 때문이다.
 *
 * **파일은 다르다.** 쓰는 도중에 프로세스가 죽으면 **레코드가 반쪽만 남는다.**
 * 아무도 그것을 막아 주지 않는다. 그 반쪽을 멀쩡한 레코드로 읽으면 길이
 * 필드에 쓰레기가 들어 있어 엉뚱한 크기를 할당하려 들거나, 그럴듯한 값으로
 * 해석되어 **없던 주문이 되살아난다.**
 *
 * 그래서 레코드마다 길이와 CRC를 둔다. 둘 다 맞아야 그 레코드를 인정한다.
 *
 * ===========================================================================
 * 찢어진 꼬리는 버린다. 고치지 않는다
 * ===========================================================================
 *
 * 마지막 레코드가 반쪽이면 그 앞까지만 재생하고 멈춘다. **고치려 들지
 * 않는다** — 반쪽 레코드에서 나머지를 지어내는 것은 없던 입력을 만드는 일이다.
 *
 * 그 앞까지는 온전하다. 덧붙이기만 했으므로 앞쪽이 뒤에 의해 바뀌지 않는다.
 *
 * ===========================================================================
 * 기본은 레코드마다 디스크에 밀어 넣는다
 * ===========================================================================
 *
 * `fsync`는 비싸다. 묶어서 하면 훨씬 빠르지만, **묶은 만큼이 통째로 사라질 수
 * 있다.** 전원이 끊기면 커널 버퍼에만 있던 것은 없던 일이 된다.
 *
 * 이 저널의 쓰임은 "재기동 뒤 되살리기"이므로 **잃으면 안 되는 것**이다.
 * 그래서 기본은 매 레코드 `fsync`다. **빠른 것보다 틀리기 어려운 것**을
 * 기본으로 둔다 — 이 프로젝트가 되풀이한 선택이다.
 */

/* "MSJ1". 남의 파일을 열었을 때 빨리 알아채려고 레코드마다 둔다. */
#define JOURNAL_MAGIC 0x4D534A31u

/* 레코드 하나의 실을 것 상한. 전문(64KB)보다 넉넉하다. */
#define JOURNAL_PAYLOAD_MAX 65536u

/* 레코드 머리: magic(4) type(1) rsv(3) len(4) seq(8) ts(8) */
#define JOURNAL_HEADER_LEN 28u

/* 머리 뒤 실을 것, 그 뒤 CRC(4). */
#define JOURNAL_CRC_LEN 4u

typedef struct journal journal_t;

/* 재생할 때 레코드 하나를 넘겨받는 모양. */
typedef struct {
    uint8_t        type;
    uint64_t       seq;
    int64_t        ts; /* 논리 시각. 시스템 시각이 아니다 */
    const uint8_t *payload;
    uint32_t       len;
} jrec_t;

/*
 * 재생 콜백. 0이 아닌 값을 돌려주면 거기서 멈춘다.
 * `payload`는 **다음 호출까지만 유효하다.**
 */
typedef int (*journal_fn)(const jrec_t *rec, void *ctx);

/* 덧붙이기용으로 연다. 없으면 만든다. 실패하면 NULL. */
journal_t *journal_create(const char *path);

/* 읽기용으로 연다. 없으면 NULL. */
journal_t *journal_open_read(const char *path);

void journal_close(journal_t *j);

/*
 * 레코드 하나를 덧붙인다.
 *
 * 성공하면 ERR_OK. `len`이 한도를 넘으면 ERR_INVALID_ARG,
 * 쓰기가 실패하면 ERR_IO.
 *
 * **머리·실을 것·CRC를 한 번의 쓰기로 낸다.** 나눠 쓰면 그 사이에 죽었을 때
 * 찢어질 자리가 하나 더 는다.
 */
int journal_append(journal_t *j, uint8_t type, uint64_t seq, int64_t ts,
                   const uint8_t *payload, uint32_t len);

/* 커널 버퍼에 있는 것까지 디스크로 민다. */
int journal_sync(journal_t *j);

/*
 * 처음부터 끝까지 재생한다. 읽어 넘긴 레코드 수를 돌려준다.
 *
 * **찢어진 꼬리를 만나면 거기서 멈춘다**(그 앞까지는 유효하다).
 * `out_truncated`가 NULL이 아니면 꼬리가 찢어져 있었는지를 담는다 —
 * 조용히 넘어가면 "원래 거기까지였다"와 구분되지 않는다.
 *
 * 콜백이 0이 아닌 값을 돌려주면 그 값을 그대로 돌려준다(음수 에러 포함).
 */
int journal_replay(journal_t *j, journal_fn fn, void *ctx, bool *out_truncated);

/* 지금까지 덧붙인 레코드 수(이 핸들 기준). */
int64_t journal_count(const journal_t *j);

/* CRC32. 테스트가 직접 확인할 수 있게 열어 둔다. */
uint32_t journal_crc32(const uint8_t *data, size_t len);

#endif /* MINI_SOR_JOURNAL_H */
