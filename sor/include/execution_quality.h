#ifndef MINI_SOR_EXECUTION_QUALITY_H
#define MINI_SOR_EXECUTION_QUALITY_H

#include <stdbool.h>
#include <stdint.h>

#include "consolidated.h"
#include "order.h"
#include "types.h"

/*
 * 집행 품질 측정.
 *
 * **이 프로젝트의 최종 산출물이 여기서 나온다.** "집행 전략별로 평균 체결 단가가
 * 얼마나 달랐는가"를 재는 자가 이 파일이다.
 *
 * ===========================================================================
 * 기준가를 무엇으로 할 것인가 (완료 조건이 요구한 문서화)
 * ===========================================================================
 *
 * **접수 시점의 통합 최우선 상대호가(arrival price)를 쓴다.**
 *
 * 후보가 셋이었다.
 *
 *  1. **주문의 지정가** — 주문자가 정한 값이다. 시장 상태를 전혀 반영하지 않으므로,
 *     지정가를 보수적으로 적어 넣기만 해도 슬리피지가 저절로 좋아 보인다.
 *     잣대가 측정 대상에 조종당한다
 *  2. **중간가** — 매수·매도 호가의 가운데. 한쪽 호가가 비면 **정의되지 않는다.**
 *     이 시뮬레이터의 시나리오에는 한쪽만 있는 경우가 흔해서 측정에 구멍이 생긴다
 *  3. **접수 시점 통합 최우선 상대호가** — 채택
 *
 * 3을 고른 결정적인 이유는 **전략 비교가 목적**이라는 것이다.
 *
 * 기준가를 시장별로 잡으면 KRX_ONLY는 KRX 호가로, BEST_PRICE는 NXT 호가로 재게 된다.
 * 서로 다른 잣대로 잰 값을 나란히 놓고 "몇 bp 좋아졌다"고 말할 수 없다.
 * **통합** 최우선호가는 전략이 무엇이든 같은 값이므로 공통 잣대가 된다.
 *
 * "접수 시점"인 것도 같은 이유다. 집행이 끝난 뒤의 호가는 그 집행이 밀어 놓은
 * 결과라서, 자기가 만든 변화를 자기 기준으로 삼는 순환이 된다.
 *
 * ===========================================================================
 * bp 환산과 반올림 (완료 조건이 요구한 문서화)
 * ===========================================================================
 *
 * 1bp = 0.01% = 1/10,000.
 *
 * **0에서 먼 쪽으로 반올림한다(round half away from zero).** 나머지의 두 배가
 * 나누는 수 이상이면 절댓값을 1 올린다. 부호는 절댓값에 적용하므로 매수와 매도가
 * 대칭이다 — 같은 크기의 불리함이 방향만 다르다고 다른 값이 되면 안 된다.
 *
 * 버림(0 방향)을 쓰지 않은 이유: 0.6bp의 슬리피지가 0bp로 보고된다. 손해를
 * 낙관적으로 표시하는 규칙은 측정 도구로 쓸 수 없다.
 *
 * **bp는 평균 단가가 아니라 체결 금액에서 직접 낸다.**
 *
 * 평균 단가는 정수라 최대 1원의 버림 오차를 갖는다. 10,000원짜리 주식에서 1원은
 * 정확히 1bp다 — 우리가 재려는 크기와 같다. 평균 단가를 거쳐 bp를 내면 그 오차가
 * 결과를 그대로 흔든다. 그래서 표시용 평균 단가(원)와 측정용 bp를 따로 계산한다.
 *
 * ===========================================================================
 * 부호 규약
 * ===========================================================================
 *
 * **슬리피지는 불리할수록 양수다.** 매수는 (평균 단가 - 기준가), 매도는
 * (기준가 - 평균 단가). 그래야 매수와 매도를 한 표에 놓고 비교할 수 있다.
 */

/* 100% = 10,000bp. */
#define BP_SCALE 10000

/* 한 논리 주문의 집행 품질. */
typedef struct {
    side_t  side;
    qty_t   order_qty;
    qty_t   filled_qty;
    int64_t notional;  /* 체결 금액 합 */
    price_t benchmark; /* 접수 시점 통합 최우선 상대호가 */

    price_t avg_price;    /* 체결금액 / 체결수량. 버림. 표시용 */
    int64_t slippage;     /* 원. 불리할수록 양수 */
    int32_t slippage_bp;  /* 체결금액에서 직접. 불리할수록 양수 */
    int32_t fill_rate_bp; /* 10000bp = 100% */
} eq_metrics_t;

/*
 * 값을 기준 대비 bp로 환산한다. 0에서 먼 쪽으로 반올림.
 * base가 0 이하면 0을 반환한다 — 나눌 기준이 없으면 비율도 없다.
 */
int32_t eq_to_bp(int64_t value, int64_t base);

/* 평균 체결 단가. 체결이 없으면 0. */
price_t eq_avg_price(int64_t notional, qty_t filled_qty);

/*
 * 접수 시점의 기준가를 잡는다.
 *
 * 매수면 통합 최우선 매도호가, 매도면 통합 최우선 매수호가다. 열린 시장 중
 * 가장 유리한 호가를 쓴다 — 통합 호가창(T2-01)이 답을 이미 알고 있다.
 * 어느 시장에도 상대 호가가 없으면 ERR_NO_LIQUIDITY.
 *
 * **집행 전에 불러야 한다.** 집행이 끝난 뒤의 호가는 그 집행의 결과다.
 */
int eq_benchmark(const cons_book_t *cons, const order_t *req, ts_t ts,
                 price_t *out_benchmark);

/*
 * 집행 결과를 품질 지표로 바꾼다.
 *
 * filled_qty가 0이면 평균 단가와 슬리피지는 0이고 체결률만 0으로 남는다 —
 * 체결이 없었다는 사실 자체가 결과다.
 *
 * benchmark가 0 이하면 ERR_INVALID_PRICE, 수량이 맞지 않으면 ERR_INVALID_QTY.
 */
int eq_measure(side_t side, qty_t order_qty, qty_t filled_qty, int64_t notional,
               price_t benchmark, eq_metrics_t *out);

#endif /* MINI_SOR_EXECUTION_QUALITY_H */
