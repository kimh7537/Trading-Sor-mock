#ifndef MINI_SOR_ORDMAP_H
#define MINI_SOR_ORDMAP_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "types.h"

/*
 * FEP — 주문번호 매핑.
 *
 * ===========================================================================
 * T2-09가 이은 곳에서 한 칸 더 나간다
 * ===========================================================================
 *
 * T2-09(`sor/order_map.c`)는 **논리 주문 ↔ 물리 주문**을 이었다. 사용자가 낸
 * 주문 하나가 시장별로 쪼개진 다리들과 어떻게 대응하는지까지다.
 *
 * 그 바깥이 남았다. **물리 주문을 거래소에 보내면 거래소가 자기 번호를 붙여
 * 돌려준다.** 이후 체결 통보는 그 번호로 온다. 우리 번호와 거래소 번호를
 * 잇는 것이 여기다.
 *
 *   사용자 주문 ──(T2-09)── 물리 주문 ──(여기)── 거래소 주문번호
 *
 * ===========================================================================
 * 거래소 번호는 우리가 고를 수 없다
 * ===========================================================================
 *
 * T2-09는 `phys = logical × 16 + market + 1`이라는 **산술**로 번호를 만들어
 * 해시 없이 양방향 조회를 얻었다. 번호를 우리가 정했기 때문에 가능했다.
 *
 * 거래소 번호는 거래소가 정한다. 규칙도 범위도 우리가 모른다. 그래서 산술로는
 * 안 되고 **찾아야** 한다.
 *
 * **선형 탐색으로 시작한다.** 표가 `ORDMAP_MAX`개이므로 최악이 그만큼이다.
 * 해시 색인을 두면 O(1)이 되지만, CLAUDE.md는 "성능 최적화를 먼저 하기"를
 * 금지한다 — 이 계층이 느린지 재 본 적이 없다.
 *
 * ponytail: 선형 탐색이다. 체결이 몰릴 때 이 계층이 병목으로 재이면
 * `cl_ord_id`·거래소 번호 각각에 개방 주소법 색인을 얹는다. 그 변경은 이
 * 파일 안에서 끝난다 — 바깥은 `find_by_*`만 부른다.
 *
 * ===========================================================================
 * 응답 전에 취소가 오면 — **우리 번호로 보낸다**
 * ===========================================================================
 *
 * 주문을 보내고 응답을 받기 전에 사용자가 취소를 누를 수 있다. 그때 우리는
 * 거래소 번호를 모른다. 셋 중 하나를 해야 한다.
 *
 *  (a) **거절** — "아직 접수 확인 전입니다". 사용자가 다시 눌러야 한다
 *  (b) **보류** — 응답이 오면 그때 취소를 보낸다
 *  (c) **우리 번호로 보낸다** — `CANCEL_REQ`에 `order_id = 0`, `cl_ord_id`만
 *
 * **(c)다.** `CANCEL_REQ`가 두 번호를 **모두** 싣도록 설계돼 있다(T3-02).
 * 거래소가 주문을 받았다면 우리 번호로 찾아 취소하고, 받지 못했다면 "없는
 * 주문"으로 깔끔하게 거부한다. **어느 쪽이든 모호함이 남지 않는다.**
 *
 * (a)는 사용자에게 일을 떠넘긴다. (b)는 **취소를 늦춘다** — 빠르게 움직이는
 * 시장에서 그 지연은 돈이다. 게다가 보류한 취소를 들고 있다가 세션이 끊기면
 * 그 취소는 어떻게 되는가? T3-14가 풀어야 할 문제를 하나 더 만드는 셈이다.
 *
 * ===========================================================================
 * 가득 차면 조용히 덮지 않는다
 * ===========================================================================
 *
 * 살아 있는 주문의 매핑을 잃으면 **그 주문의 체결 통보가 어디에도 붙지 않는다.**
 * 그래서 자리를 만들 때 **끝난 주문부터** 밀어낸다. 끝난 것조차 없으면
 * 거절한다(`ERR_POOL_EXHAUSTED`) — T3-10이 큐가 찼을 때 한 것과 같다.
 *
 * 끝난 주문을 곧바로 지우지 않고 남겨 두는 이유는 **늦게 오는 체결** 때문이다.
 * 취소했다고 생각한 주문에 체결이 하나 더 붙는 일은 실제로 일어난다. 남겨
 * 두면 그 체결이 제 주문을 찾는다.
 */

/* 한 접속이 동시에 들고 있을 수 있는 주문 수. */
#define ORDMAP_MAX 4096

typedef enum {
    /* 빈 칸. */
    ORD_NONE = 0,
    /* 보냈지만 아직 응답이 없다. **거래소 번호를 모른다.** */
    ORD_PENDING,
    /* 접수됐다. 거래소 번호가 있다. */
    ORD_LIVE,
    /* 끝났다(거부·전량체결·취소). 늦게 오는 체결을 위해 남겨 둔다. */
    ORD_DONE,
    /*
     * **판정 보류**(T3-14). 응답을 못 받은 채 접속이 끊겼다.
     * 거래소가 못 받았는지, 받고 접수했는지, 받고 거부했는지 **알 수 없다.**
     */
    ORD_INDOUBT
} ord_state_t;

typedef struct {
    ord_state_t state;
    uint64_t    cl_ord_id; /* 우리 번호. T2-09의 물리 주문번호 */
    order_id_t  exch_id;   /* 거래소가 매긴 번호. PENDING이면 0 */
    uint64_t    added_seq; /* 들어온 차례. 밀어낼 것을 고를 때 쓴다 */
} ordent_t;

typedef struct {
    ordent_t ent[ORDMAP_MAX];
    uint64_t next_seq;
    int32_t  count; /* 비어 있지 않은 칸 수 */
} ordmap_t;

void ordmap_init(ordmap_t *m);

/*
 * 주문을 보내면서 등록한다. 상태는 ORD_PENDING.
 *
 * `cl_ord_id`가 0이면 ERR_INVALID_ARG — 0은 "없음"의 뜻으로 쓴다.
 * 이미 있는 번호면 ERR_DUPLICATE. **덮어쓰지 않는다** — 같은 번호를 두 주문에
 * 쓰는 것은 호출부의 버그이고, 덮으면 앞 주문의 체결이 갈 곳을 잃는다.
 *
 * 자리가 없으면 끝난 주문 중 가장 오래된 것을 밀어낸다. 그것도 없으면
 * ERR_POOL_EXHAUSTED.
 */
int ordmap_add(ordmap_t *m, uint64_t cl_ord_id);

/*
 * 거래소 응답을 반영한다.
 *
 * `accepted`면 ORD_LIVE가 되고 `exch_id`를 기록한다. 거부면 ORD_DONE이고
 * `exch_id`는 무시한다 — 거부된 주문에는 거래소 번호가 없다.
 *
 * 모르는 `cl_ord_id`면 ERR_NOT_FOUND. 접수인데 `exch_id`가 0이면
 * ERR_INVALID_ARG — 번호 없이 접수될 수는 없다.
 * 이미 다른 번호로 접수돼 있으면 ERR_DUPLICATE.
 */
int ordmap_on_ack(ordmap_t *m, uint64_t cl_ord_id, order_id_t exch_id,
                  bool accepted);

/* 끝났다고 표시한다(전량체결·취소). 모르는 번호면 ERR_NOT_FOUND. */
int ordmap_close(ordmap_t *m, uint64_t cl_ord_id);

/* 없으면 NULL. 돌려준 포인터는 다음 `ordmap_add`까지만 유효하다. */
const ordent_t *ordmap_find_by_cl(const ordmap_t *m, uint64_t cl_ord_id);

/*
 * 거래소 번호로 찾는다. 체결 통보가 이 길로 들어온다.
 * PENDING 항목은 거래소 번호가 없으므로 걸리지 않는다.
 */
const ordent_t *ordmap_find_by_exch(const ordmap_t *m, order_id_t exch_id);

/*
 * 취소 전문에 실을 거래소 번호를 알려 준다.
 *
 * 접수된 주문이면 그 번호를, **아직 응답 전이면 0**을 담는다. 0은 "우리
 * 번호로 찾아라"라는 뜻이다(헤더의 설명 참조).
 *
 * 모르는 번호면 ERR_NOT_FOUND. 이미 끝난 주문이면 ERR_NOT_SUPPORTED —
 * 끝난 주문을 취소하겠다는 것은 호출부가 상태를 잘못 알고 있다는 뜻이다.
 */
int ordmap_cancel_key(const ordmap_t *m, uint64_t cl_ord_id,
                      order_id_t *out_exch_id);

/* 비어 있지 않은 칸 수. */
int32_t ordmap_count(const ordmap_t *m);

/* 아직 끝나지 않은 주문 수(PENDING + LIVE + INDOUBT). */
int32_t ordmap_live_count(const ordmap_t *m);

/* ===========================================================================
 * T3-14 — 세션이 끊겼을 때의 판정
 * ===========================================================================
 *
 * 응답을 못 받은 주문은 끊긴 순간 **세 갈래 중 어느 것인지 알 수 없다.**
 *
 *   1. 거래소가 전문을 못 받았다        -> 주문은 없다
 *   2. 받고 접수했다                     -> 살아 있는 주문이 있다
 *   3. 받고 거부했다                     -> 주문은 없다
 *
 * 우리 쪽 정보만으로는 1과 2를 가를 수 없다. 보낸 것은 확실하지만 **닿았는지는
 * 모른다.**
 *
 * ---------------------------------------------------------------------------
 * 단정하지 않는다
 * ---------------------------------------------------------------------------
 *
 * "어차피 응답이 없었으니 거부로 치자"가 가장 흔한 처리이고 **가장 위험하다.**
 * 실제로는 접수돼 있었다면 우리가 모르는 포지션이 생긴다 — 체결 통보가 와도
 * 붙일 주문이 없고, 장이 끝난 뒤 잔고가 맞지 않는 것으로 드러난다.
 *
 * 반대로 "접수됐겠지"도 안 된다. 없는 주문을 취소하려 들고, 있지도 않은
 * 포지션을 근거로 다음 주문을 낸다.
 *
 * **모르는 것은 모른다고 표시한다.** 그것이 `ORD_INDOUBT`다.
 *
 * ---------------------------------------------------------------------------
 * 자동으로 다시 보내지 않는다
 * ---------------------------------------------------------------------------
 *
 * 재전송은 **중복 주문**을 만들 수 있다. 1번이면 맞는 처리지만 2번이면 같은
 * 주문이 둘이 된다 — 이 계층이 저지를 수 있는 가장 비싼 실수다.
 * 그래서 이 모듈은 **아무것도 다시 보내지 않는다.** 판정만 한다.
 *
 * ---------------------------------------------------------------------------
 * 조회로 판정한다
 * ---------------------------------------------------------------------------
 *
 * 다시 붙은 뒤 거래소에 **당일 전체 주문을 조회**한다(`QUERY_REQ`의
 * `order_id = 0`). 응답(`QUERY_ACK`)에는 우리 번호가 실려 오므로 되짚을 수 있다.
 *
 * **조회 응답에 없던 주문은 거래소에 없다** — 이것이 1번과 2번을 가르는
 * 유일한 근거다. 그런데 그 결론은 **"응답이 끝났다"를 알아야만** 낼 수 있다.
 * 아직 안 온 것과 정말 없는 것이 구분되지 않기 때문이다. 그래서 `QUERY_ACK`에
 * **마지막 표시**를 두었다(T3-14에서 더한 필드).
 *
 * 전제: 조회는 **당일 전체**이지 미체결만이 아니다. 미체결만 돌려준다면 이미
 * 체결된 주문이 "없는 주문"으로 판정되어, 있었던 체결을 없다고 말하게 된다.
 */

/*
 * 접속이 끊겼다. **응답 못 받은 주문을 판정 보류로 옮긴다.**
 * 옮긴 건수를 돌려준다. 이미 접수된(LIVE) 주문은 건드리지 않는다 —
 * 그것은 거래소에 있다는 것을 아는 주문이다.
 */
int32_t ordmap_on_disconnect(ordmap_t *m);

/*
 * 조회 응답 한 건을 반영한다.
 *
 * `live`면 거래소에 살아 있다는 뜻이라 ORD_LIVE가 되고 `exch_id`를 기록한다.
 * 아니면(체결 완료·취소·거부) ORD_DONE이다.
 *
 * 모르는 번호면 ERR_NOT_FOUND — 우리가 보낸 적 없는 주문을 거래소가 알고
 * 있다는 뜻이고, 그것은 이 계층이 판단할 일이 아니다.
 */
int ordmap_on_query_result(ordmap_t *m, uint64_t cl_ord_id, order_id_t exch_id,
                           bool live);

/*
 * 조회가 끝났다(마지막 표시를 받았다). **응답에 없던 판정 보류 주문을
 * "거래소에 없음"으로 판정한다.** 판정한 건수를 돌려준다.
 *
 * 이 함수는 **마지막 표시를 실제로 받았을 때만** 불러야 한다. 조회가 도중에
 * 끊겼는데 부르면 아직 안 온 주문을 없다고 판정한다.
 */
int32_t ordmap_finish_query(ordmap_t *m);

/*
 * 판정 보류 건수. **0이 아니면 사람이 알아야 한다** — 우리도 거래소도
 * 답을 주지 못한 주문이 있다는 뜻이다.
 */
int32_t ordmap_indoubt_count(const ordmap_t *m);

/*
 * 판정 보류 주문을 차례로 꺼낸다. `*cursor`는 0으로 시작해 넘겨 준다.
 * 없으면 NULL. 무엇이 보류 중인지 보고할 때 쓴다.
 */
const ordent_t *ordmap_next_indoubt(const ordmap_t *m, int32_t *cursor);

#endif /* MINI_SOR_ORDMAP_H */
