#ifndef MINI_SOR_FRAMER_H
#define MINI_SOR_FRAMER_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "wire.h"

/*
 * FEP 공통 — 전문 조립.
 *
 * T3-08의 이벤트 루프는 "읽을 것이 있다"까지만 알려 준다. 그 다음이 여기다.
 *
 * ===========================================================================
 * TCP는 전문 경계를 지켜 주지 않는다
 * ===========================================================================
 *
 * 상대가 70바이트짜리 전문을 한 번에 `write`해도 수신 쪽에서 한 번에 70바이트가
 * 오리라는 보장은 없다. 경로의 MTU, 나글 알고리즘, 수신 버퍼 사정에 따라
 * **24바이트 헤더가 세 조각으로 쪼개져** 올 수도 있고, 반대로 **전문 세 개가
 * 한 번에** 올 수도 있다.
 *
 * 그래서 `read`가 돌려준 것을 그대로 전문으로 보면 안 된다. 쌓아 두고, 완성된
 * 것만 꺼낸다.
 *
 * T3-03의 원장 리스너는 이 문제를 `read_exact()`로 피했다 — 필요한 만큼 올
 * 때까지 **블로킹으로 기다린다.** 한 번에 한 접속만 다루니 그래도 됐다.
 * FEP는 접속을 여러 개 다루므로 기다릴 수 없다. 기다리지 않으려면 조립 상태를
 * 접속마다 들고 있어야 하고, 그것이 `framer_t`다.
 *
 * ===========================================================================
 * 어긋난 전문을 만나면 **재동기하지 않고 끊는다**
 * ===========================================================================
 *
 * magic이 "MS"가 아니거나 version이 다르면 두 가지를 할 수 있다.
 *
 *  (a) **재동기** — 앞으로 훑으며 다음 "MS"를 찾아 거기서부터 다시 읽는다
 *  (b) **중단** — 스트림을 버리고 접속을 끊는다
 *
 * **(b)를 고른다.** 재동기는 바이트가 유실될 수 있는 전송(직렬 회선, UDP)에서
 * 쓰는 기법이다. TCP는 순서와 완전성을 보장하므로, 여기서 magic이 어긋났다는
 * 것은 **바이트가 빠진 게 아니라 우리 쪽 조립 상태가 이미 틀렸다**는 뜻이다.
 * 틀린 상태에서 앞으로 훑으면 "MS"(0x4D53)는 금방 다시 나온다 — 가격 필드
 * 안에서도, 계좌번호 안에서도 나온다. 그러면 **그럴듯하지만 거짓인 전문**이
 * 만들어지고, 그것은 접속이 끊기는 것보다 훨씬 나쁘다. 주문 한 건이 엉뚱한
 * 수량으로 해석될 수 있다.
 *
 * 끊으면 T3-11의 재접속이 처음부터 다시 맞춘다. **틀린 채로 계속 가는 것보다
 * 처음부터 다시 하는 편이 싸다.**
 *
 * ===========================================================================
 * body 포인터의 수명
 * ===========================================================================
 *
 * `framer_next()`가 돌려주는 body 포인터는 **`framer_t` 안의 버퍼를 가리킨다.**
 * 전문마다 할당하지 않으므로(핫 패스에서 `malloc` 금지) 그 자리는 재사용된다.
 *
 * **다음 `framer_next()`나 `framer_push()`를 부르면 무효가 된다.**
 * 그 뒤에도 내용이 필요하면 호출부가 복사한다.
 */

typedef struct {
    uint8_t buf[WIRE_FRAME_MAX];
    size_t  off; /* 아직 안 꺼낸 첫 바이트 */
    size_t  len; /* 쌓인 바이트의 끝 */
    int     err;    /* 한 번 어긋나면 이 접속은 끝이다. 그 에러 코드를 남긴다 */
} framer_t;

void framer_init(framer_t *fr);

/*
 * 받은 바이트를 넣는다. 성공하면 ERR_OK.
 *
 * 자리가 모자라면 ERR_POOL_EXHAUSTED. 버퍼는 전문 하나가 통째로 들어갈 만큼
 * 크므로, 모자란다는 것은 꺼내지 않고 계속 넣기만 했다는 뜻이다.
 * 이미 어긋난 상태면 ERR_NOT_SUPPORTED — 더 받아 봐야 소용없다.
 */
int framer_push(framer_t *fr, const uint8_t *data, size_t n);

/*
 * 완성된 전문 하나를 꺼낸다.
 *
 *   1  꺼냈다. `hdr`과 `body`가 채워진다 (body_len이 0이면 body는 유효하지만
 *      읽을 것이 없다)
 *   0  아직 모자라다. 더 받아야 한다
 *  음수 어긋났다. **접속을 끊어야 한다.** 이후 호출은 계속 같은 값을 준다
 *
 * 0이 나올 때까지 되풀이해 부른다 — 한 번의 `push`에 전문이 여러 개 들어 있을
 * 수 있다.
 */
int framer_next(framer_t *fr, wire_header_t *hdr, const uint8_t **body);

/* 아직 꺼내지 않고 쌓여 있는 바이트 수. */
size_t framer_pending(const framer_t *fr);

/* 어긋나서 버려야 하는 상태인가. */
bool framer_broken(const framer_t *fr);

#endif /* MINI_SOR_FRAMER_H */
