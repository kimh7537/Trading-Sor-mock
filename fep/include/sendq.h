#ifndef MINI_SOR_SENDQ_H
#define MINI_SOR_SENDQ_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "wire.h"

/*
 * FEP 공통 — 송신 큐.
 *
 * T3-09가 받는 쪽이었다면 여기는 보내는 쪽이다.
 *
 * ===========================================================================
 * 논블로킹에서 write는 일부만 쓴다
 * ===========================================================================
 *
 * 블로킹 소켓의 `write`는 다 쓸 때까지 돌아오지 않는다. 논블로킹은 다르다.
 *
 *  - 커널 송신 버퍼에 자리가 있는 만큼만 쓰고 **그 바이트 수를 돌려준다**
 *  - 자리가 아예 없으면 -1 / `EAGAIN`
 *
 * **둘 다 에러가 아니다.** 상대가 느리거나 경로가 막혔다는 뜻일 뿐이다.
 * 남은 것을 들고 있다가 다시 쓸 수 있을 때 이어 보내면 된다. 그 "들고 있는
 * 자리"가 이 큐다.
 *
 * T3-03의 원장은 `write_exact()`로 이 문제를 피했다 — 다 나갈 때까지 블로킹으로
 * 기다린다. FEP는 접속을 여러 개 다루므로 기다릴 수 없다.
 *
 * ===========================================================================
 * 전문을 반만 넣지 않는다
 * ===========================================================================
 *
 * 자리가 70바이트 남았는데 100바이트짜리 전문이 오면, 70바이트만 넣고 나머지를
 * 나중에 넣는 방법이 있다. **하지 않는다.**
 *
 * 그 70바이트는 이미 나가 버릴 수 있고, 그러면 받는 쪽은 길이가 맞지 않는
 * 전문을 보게 된다. T3-09의 판단대로 받는 쪽은 **재동기하지 않고 접속을 끊는다.**
 * 한 전문을 못 보내는 것과 접속이 끊기는 것은 무게가 다르다.
 *
 * 그래서 **전부 아니면 전무**다. 자리가 모자라면 `ERR_POOL_EXHAUSTED`.
 *
 * ===========================================================================
 * 가득 찼을 때 버리지 않는다 — 호출부에 알린다
 * ===========================================================================
 *
 * 큐가 차면 흔히 세 가지를 한다. (a) 오래된 것을 버린다 (b) 새 것을 버린다
 * (c) 넣으려는 쪽에 실패를 알린다.
 *
 * **(c)다.** 여기 흐르는 것은 주문과 취소다. **조용히 버린 주문은 "보냈는데
 * 응답이 없는 주문"과 구분되지 않는다** — T3-14가 풀어야 할 가장 어려운 문제를
 * 이 계층이 스스로 만드는 셈이다. 실패를 돌려주면 호출부가 정한다: 거부로
 * 응답하든, 접속을 끊고 다시 붙든.
 *
 * 큐가 찬다는 것은 상대가 우리가 보내는 속도를 못 따라온다는 뜻이다.
 * 그 사실은 숨기지 말고 위로 올려야 한다.
 *
 * ===========================================================================
 * EV_WRITE는 보낼 것이 있을 때만 켠다
 * ===========================================================================
 *
 * T3-08은 **레벨 트리거**다. 소켓은 송신 버퍼에 자리가 있는 한 "쓸 수 있음"이
 * 계속 참이고, 보통은 늘 자리가 있다. `EPOLLOUT`을 켜 둔 채로 두면 루프가
 * **아무것도 보낼 게 없는데 쉬지 않고 깨어난다.**
 *
 * 그래서 `sendq_want_write()`가 참일 때만 `EV_WRITE`를 얹는다. 큐가 비면 내린다.
 * 켜고 내리는 것은 호출부(T3-11의 세션)가 `evloop_mod()`로 한다 — 큐는 이벤트
 * 루프를 알지 못한다.
 */

/*
 * 큐 크기.
 *
 * 전문 하나(최대 64KB + 24)가 반드시 들어가야 하고, 상대가 잠깐 느려졌을 때
 * 몇 개를 쌓아 둘 여유가 있어야 한다. 256KB면 가장 큰 전문 네 개, 보통 크기
 * (70바이트 안팎)로는 수천 개다. 접속마다 하나씩이므로 접속이 몇 개인 FEP에서
 * 문제가 되지 않는다.
 */
#define SENDQ_CAP 262144u

typedef struct {
    uint8_t buf[SENDQ_CAP];
    size_t  off; /* 아직 안 보낸 첫 바이트 */
    size_t  len; /* 쌓인 바이트의 끝 */
} sendq_t;

void sendq_init(sendq_t *q);

/*
 * 전문 하나를 큐에 넣는다. **전부 아니면 전무.**
 *
 * 성공하면 ERR_OK. 자리가 모자라면 ERR_POOL_EXHAUSTED이고 **큐는 그대로다.**
 * n이 0이거나 SENDQ_CAP을 넘으면 ERR_INVALID_ARG.
 */
int sendq_push(sendq_t *q, const uint8_t *frame, size_t n);

/*
 * 보낼 수 있는 만큼 보낸다.
 *
 *   >= 0  이번에 보낸 바이트 수. **0도 정상이다**(EAGAIN — 자리가 없다)
 *   음수   상대가 끊겼거나 소켓이 잘못됐다. ERR_IO
 *
 * 부분 쓰기는 에러가 아니다. 남은 것은 큐에 그대로 있고 `sendq_pending()`이
 * 얼마인지 말해 준다.
 */
int sendq_flush(sendq_t *q, int fd);

/* 아직 못 보낸 바이트 수. */
size_t sendq_pending(const sendq_t *q);

/* EV_WRITE를 켜 두어야 하는가. 보낼 것이 있을 때만 참이다. */
bool sendq_want_write(const sendq_t *q);

#endif /* MINI_SOR_SENDQ_H */
