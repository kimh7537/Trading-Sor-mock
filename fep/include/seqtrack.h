#ifndef MINI_SOR_SEQTRACK_H
#define MINI_SOR_SEQTRACK_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "wire.h"

/*
 * FEP — 시퀀스 갭 감지와 재전송 보관.
 *
 * 전문 헤더(T3-01)에는 보내는 쪽 기준의 `seq`가 있다. 여기는 그 번호로
 * **빠진 것이 있는지 알아내고, 빠진 것을 다시 받아 채우는** 자리다.
 *
 * ===========================================================================
 * TCP를 쓰는데 왜 갭이 생기나
 * ===========================================================================
 *
 * 한 접속 안에서는 생기지 않는다. TCP가 순서와 완전성을 보장한다.
 * 갭이 생기는 곳은 **접속과 접속 사이**다 — 우리가 끊겨 있는 동안 상대가
 * 보낸 체결 통보는 어디에도 남지 않는다. 다시 붙었을 때 "14번 다음이 21번"을
 * 보게 되고, 그 사이 여섯 건이 우리가 못 본 체결이다.
 *
 * 한 접속 안에서 갭이 보인다면 그것은 **상대가 번호를 잘못 매기고 있다**는
 * 뜻이다. 그때도 조용히 넘어가지 않는다 — 감지는 늘 돌아간다.
 *
 * ===========================================================================
 * 갭을 만나면 "그 앞부터 다시"를 요청하고, 그동안 오는 것은 버린다
 * ===========================================================================
 *
 * 순서를 지키려면 두 가지 중 하나를 해야 한다.
 *
 *  (a) **보류** — 갭 뒤에 온 전문을 따로 쌓아 두었다가, 빠진 것이 채워지면
 *      순서대로 꺼낸다. 재정렬 버퍼가 필요하다
 *  (b) **버리고 다시 받기** — 갭을 만나면 "빠진 번호부터 전부 다시"를
 *      요청하고, 그 사이 도착하는 것은 버린다. 상대가 다시 보내 주므로
 *      결국 순서대로 다 받는다
 *
 * **(b)를 고른다.** (a)의 재정렬 버퍼는 "얼마나 쌓아 둘 것인가", "쌓아 둔 채
 * 갭이 안 채워지면 어쩔 것인가"를 또 정해야 하고, 그 두 질문의 답이 틀리면
 * **조용히 순서가 뒤바뀐 채 위로 올라간다.** 체결 통보의 순서가 뒤바뀌면
 * 잔량 계산이 어긋나는데, 그런 버그는 한참 뒤에 잔고가 안 맞을 때 드러난다.
 *
 * (b)가 치르는 값은 **이미 본 전문을 한 번 더 받는 것**이다. 이 계층의 전문은
 * 70바이트 안팎이고 갭은 재접속 때나 생긴다. 싼 값이다.
 *
 * (b)가 성립하려면 **중복을 반드시 버려야 한다** — 재전송은 겹쳐 오게 마련이다.
 *
 * ===========================================================================
 * 보관에 없는 구간을 요청받으면 조용히 빠뜨리지 않는다
 * ===========================================================================
 *
 * 보낸 전문을 영원히 들고 있을 수는 없으므로 고리 버퍼에 최근 것만 남긴다.
 * 요청받은 구간이 이미 밀려 나갔다면 **"그 앞은 더 없다"고 말해 줘야 한다**
 * (`GAP_FILL`). 말해 주지 않으면 받는 쪽은 오지 않을 번호를 영원히 기다리며
 * 그 뒤의 전문을 전부 버린다 — **조용히 멈춘 접속**이 된다.
 *
 * 이 프로젝트가 되풀이한 규칙이다: 못 하는 것은 못 한다고 말한다
 * (T3-10이 큐가 찼을 때 버리지 않고 알린 것과 같다).
 */

/* --- 보내는 쪽: 다시 보낼 수 있게 보관한다 --- */

/*
 * 보관할 전문 하나의 최대 크기.
 *
 * 지금 가장 큰 전문은 체결 통보(24 + 46 = 70바이트)다. 128이면 앞으로
 * 필드가 몇 개 늘어도 버틴다. 이보다 큰 전문은 보관하지 않고 거절한다 —
 * 조용히 잘라 두면 재전송 때 반쪽 전문이 나간다.
 */
#define SEQSTORE_FRAME_MAX 128

/*
 * 몇 개를 보관할 것인가.
 *
 * 256개면 하트비트 주기(5초)로만 채워도 20분이 넘고, 주문이 몰리는 구간에서도
 * 재접속에 걸리는 시간(백오프 최대 30초)보다 훨씬 길다. 한 접속에 32KB다.
 *
 * **모자라면 조용히 잃는 것이 아니라 `GAP_FILL`로 알린다.** 그래서 이 값이
 * 정확할 필요는 없고, 충분히 크기만 하면 된다.
 */
#define SEQSTORE_KEEP 256

typedef struct {
    uint64_t seq;
    uint16_t len; /* 0이면 빈 칸 */
    uint8_t  frame[SEQSTORE_FRAME_MAX];
} seqslot_t;

typedef struct {
    seqslot_t slot[SEQSTORE_KEEP];
    uint64_t  oldest; /* 아직 들고 있는 가장 오래된 seq. 비었으면 0 */
    uint64_t  newest;
    int32_t   count;
} seqstore_t;

void seqstore_init(seqstore_t *st);

/*
 * 보낸 전문을 보관한다. 고리가 차면 가장 오래된 것부터 밀려난다.
 *
 * `seq`가 0이거나 크기가 한도를 넘으면 ERR_INVALID_ARG.
 * **seq는 커지기만 해야 한다** — 되돌아가면 ERR_INVALID_ARG.
 */
int seqstore_put(seqstore_t *st, uint64_t seq, const uint8_t *frame,
                 size_t len);

/*
 * 보관 중인 전문을 꺼낸다. 성공하면 길이, 없으면 ERR_NOT_FOUND.
 * (밀려 나갔거나, 아직 보낸 적 없거나)
 */
int seqstore_get(const seqstore_t *st, uint64_t seq, uint8_t *out, size_t cap);

/* 아직 들고 있는 가장 오래된 seq. 비었으면 0. */
uint64_t seqstore_oldest(const seqstore_t *st);

/* --- 받는 쪽: 갭을 감지한다 --- */

typedef enum {
    /* 기대한 번호다. 위로 올린다. */
    SEQ_OK = 0,
    /* 이미 본 번호다. **버린다** — 재전송은 겹쳐 온다. */
    SEQ_DUP,
    /* 빠진 것이 있다. 재전송을 요청해야 한다. */
    SEQ_GAP,
    /*
     * 갭을 메우는 중이고 이건 아직 그 차례가 아니다. **버린다.**
     * 상대가 다시 보내 줄 것이다.
     */
    SEQ_WAIT
} seq_verdict_t;

typedef struct {
    uint64_t expected;   /* 다음에 받을 번호 */
    bool     recovering; /* 재전송을 기다리는 중인가 */
    uint64_t gap_from;   /* 재전송을 요청한 시작 번호 */
    int64_t  gaps;       /* 갭을 만난 횟수. 운영 지표 */
    int64_t  dups;       /* 버린 중복 수 */
} seqtrack_t;

/*
 * `first`는 처음 기대하는 번호다. 상대의 첫 전문이 1번이면 1을 준다.
 */
void seqtrack_init(seqtrack_t *tr, uint64_t first);

/*
 * 받은 번호를 판정한다. 부수 효과가 있다 — SEQ_OK면 기대값이 하나 올라간다.
 */
seq_verdict_t seqtrack_on(seqtrack_t *tr, uint64_t seq);

/*
 * 상대가 "그 앞은 더 없다"(GAP_FILL)고 알려 왔다. 기대값을 그리로 옮긴다.
 *
 * `next_seq`가 지금 기대값보다 뒤가 아니면 아무것도 하지 않고
 * ERR_INVALID_ARG — 되돌리는 요청을 받아 주면 이미 처리한 전문을 다시
 * 위로 올리게 된다.
 */
int seqtrack_skip_to(seqtrack_t *tr, uint64_t next_seq);

uint64_t seqtrack_expected(const seqtrack_t *tr);
bool     seqtrack_recovering(const seqtrack_t *tr);

#endif /* MINI_SOR_SEQTRACK_H */
