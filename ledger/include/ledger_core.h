/*
 * 원장 코어 — 주문 전문 하나를 받아 **검증 → 증거금 → 배분 → 체결 → 정산**까지
 * 끝내고 응답 전문을 만든다(T6-03).
 *
 * ===========================================================================
 * 왜 생겼나
 * ===========================================================================
 *
 * 원장 데몬(`ledgerd`)은 T3-03 때 "전문이 실제로 오가는지"만 확인하는 껍데기로
 * 세워졌다. 머리 주석에 "계좌(T3-06)와 검증(T3-07)이 들어오면 연결한다"고 적었지만
 * **끝내 연결되지 않았다.** 그래서 화면에서 주문을 내면 방향·유형·시장을 보지도 않고
 * 무조건 성공이 돌아왔다. 감사에서 찾았다.
 *
 * 조각(계좌·검증·SOR·매칭)은 각자 테스트를 통과하고 있었다. **이어 주는 코드가
 * 없었을 뿐이다.** 이 모듈이 그 이음새다.
 *
 * ===========================================================================
 * 매칭을 원장 프로세스 안에 둔다 (사용자가 고른 "최소 연결")
 * ===========================================================================
 *
 * 아키텍처 그림은 원장·SOR·FEP·거래소가 **별도 프로세스**다. 그대로 띄우려면
 * 사실상 새 Phase 규모가 든다. 사용자는 화면에서 실제로 체결되는 것을 우선했고,
 * 그래서 SOR와 매칭 엔진 2개를 이 프로세스 안에 둔다. **프로세스를 나누는 일은
 * T3-15(원장↔거래소 두 프로세스 통합 테스트)가 이미 따로 검증했다.**
 *
 * ===========================================================================
 * 호가창은 하나여야 한다 — 단일 프로세스, 단일 스레드
 * ===========================================================================
 *
 * T3-04의 워커 풀로 fork하면 **프로세스마다 호가창이 따로 생긴다.** 계좌는 공유
 * 메모리(T3-05)에 있어 공유되지만 매칭 엔진은 각자의 메모리에 있다. 같은 주문이
 * 어느 워커에 닿느냐에 따라 다른 호가창에서 체결된다 — 시장이 둘이 아니라 워커 수만큼
 * 생기는 셈이다.
 *
 * 그래서 한 프로세스가 전문을 **하나씩 차례로** 처리한다. 결정성 원칙(CLAUDE.md:
 * "매칭은 단일 스레드")과도 그대로 맞는다.
 *
 * ponytail: 접속을 한 번에 하나만 받는다(T3-03 리스너). 채널계 접속 풀을 1로 맞춰
 * 쓴다. 동시 접속자가 여럿이어야 하면 T3-08의 epoll 루프로 여러 접속을 한 스레드에서
 * 받으면 된다 — 호가창이 하나라는 조건은 그대로 지켜진다.
 *
 * ===========================================================================
 * 정산은 체결 이벤트 한 곳에서 한다
 * ===========================================================================
 *
 * 체결은 두 방향으로 일어난다. **지금 들어온 주문(taker)**이 체결되기도 하고,
 * **예전에 호가창에 걸어 둔 사용자 주문(maker)**이 나중에 체결되기도 한다.
 * 집행기(`exec_submit`)의 보고서는 앞의 것만 알려 준다.
 *
 * 매칭 엔진의 이벤트(T1-12)는 체결마다 maker와 taker 양쪽에 이벤트를 준다. 그래서
 * **돈을 옮기는 일을 그 콜백 한 곳에만 둔다.** 어느 방향으로 체결되든 같은 코드가
 * 정산한다 — 두 곳에 두면 한쪽만 고치는 날이 온다.
 *
 *  - 매수 체결 `q주 @ p`: 묶어 둔 `지정가 x q` 중 `p x q`를 예수금에서 빼며 풀고
 *    (`acct_settle`), 나머지 `(지정가 - p) x q`는 그냥 푼다(`acct_release`).
 *    maker는 늘 자기 지정가에 체결되므로 이 나머지가 0이다
 *  - 매도 체결: `p x q`를 입금한다. 매도는 증거금을 묶지 않았다(T3-07)
 *
 * **체결되지 않을 수량의 증거금은 불변식 하나로 푼다.** 묶은 돈은
 * `지정가 x 주문수량`이고, 체결분은 콜백이 풀었다. 그러면 남아야 할 묶음은
 * `지정가 x 아직 호가창에 살아 있는 수량`뿐이므로, **`주문 - 체결 - 살아 있음`
 * 만큼을 푼다.** 거부된 다리든 IOC의 남은 수량이든 경우를 따로 세지 않는다.
 *
 * ===========================================================================
 * 증거금률은 100%로 둔다
 * ===========================================================================
 *
 * 증거금률이 100% 미만이면 체결 대금 전액과 묶어 둔 증거금이 다르고, 그 차액을
 * 어디서 치를지(미수)가 별도의 주제가 된다. 이 데모는 100%로 둬서 정산이 정확히
 * 맞아떨어지게 한다. 매도의 보유 수량 확인도 범위 밖이다(T3-07에 적혀 있다).
 */

typedef struct ledger_core ledger_core_t;

/* 계좌 정원 기본값. 설정이 0이면 이 값을 쓴다. */
#define LEDGER_ACCOUNT_CAP_DEFAULT 256

typedef struct {
    const char *account; /* 데모 계좌번호. MSG_ACCOUNT_LEN(12)자 */
    int64_t     cash;    /* 처음 입금액(원) */
    const char *symbol;  /* 거래 종목 */

    price_t    ref_price;            /* 두 시장의 기준가 */
    scenario_t scenario;             /* 유동성 모양(T1-18) */
    uint64_t   seed;                 /* 유동성 생성 시드. 같은 시드 -> 같은 호가창 */
    int32_t    liquidity_per_market; /* 시장당 미리 넣는 유동성 주문 수 */
    int32_t    order_capacity;       /* 받을 수 있는 사용자 주문 수 */

    /*
     * 동시에 열어 둘 수 있는 계좌 수(T9-01). 0이면 기본값.
     *
     * 사용자마다 계좌를 하나씩 여니까 **가입 정원이 곧 이 값이다.** 계좌 하나가
     * 락까지 100바이트대라 넉넉히 잡아도 부담이 없다.
     */
    int32_t    account_capacity;

    /*
     * 다루는 종목이 국내인가 미국인가(T10-01).
     *
     * 호가 단위 표와 가격의 뜻이 여기서 갈린다 — 국내는 원, 미국은 **센트** 정수다.
     * 호가창·엔진·검증이 모두 이 값을 따라야 한다. 하나라도 어긋나면 엔진은
     * 받아들이는 가격을 검증이 막는다.
     */
    tick_table_t tick_table;
} ledger_core_config_t;

/* 화면(web)과 맞춘 기본값 — 계좌 123456789012, 005930, 기준가 70,000원. */
extern const ledger_core_config_t LEDGER_CORE_DEFAULT;

/* 설정이 잘못됐거나 자원을 못 잡으면 NULL. cfg가 NULL이면 기본값. */
ledger_core_t *ledger_core_create(const ledger_core_config_t *cfg);
void           ledger_core_destroy(ledger_core_t *core);

/*
 * 전문 하나를 처리한다. `listener_run()`의 처리 훅과 모양이 같다 — ctx에 코어를 준다.
 *
 * 응답을 out에 쓰고 길이를 돌려준다. 응답이 없는 종별이면 0, 전문 바디가 규격과
 * 다르면 음수(리스너가 접속을 끊는다).
 *
 * 주문이 거부돼도 **음수가 아니라 거부 응답**이다. 거부는 정상적인 대답이다.
 * 취소는 이 계좌의 살아 있는 물리 주문을 모두 취소하고 묶인 돈을 푼다(T7-01). 정정은
 * 아직 연결하지 않았으므로 `ERR_NOT_SUPPORTED`로 답한다 — 무조건 성공이라고 답하지 않는다.
 * 주문 상세(시장별 다리 포함)와 계좌 잔고 조회에도 답한다(T7-02). 조회는 주문번호 하나에 대해 지금 상태를 돌려준다
 * (호가창에 걸어 뒀다가 나중에 체결된 것까지 반영). 호가 조회는 한 시장의 10단을
 * 돌려준다.
 */
int ledger_core_handle(const wire_header_t *hdr, const uint8_t *body,
                       uint8_t *out, size_t out_cap, void *ctx);

/*
 * 가상 참가자가 시장마다 주문 n건을 더 낸다(T8-01 실시세 모드의 "살아 있는 호가창").
 *
 * 시드 유동성을 만든 그 생성기가 이어서 뽑는다 — 같은 시드에 같은 틱 횟수면 같은
 * 호가창이 된다. **부르지 않으면 아무 일도 없다.** 그래서 기존 테스트와 `bench`의
 * 결정성은 그대로다.
 *
 * 미체결이 무한히 쌓이면 주문 풀이 마른다. 살아 있는 가상 주문이 설정한 시장당
 * 유동성 수를 넘으면 **가장 오래된 것부터 취소한다** — 실제로도 호가는 걷힌다.
 *
 * **바깥 시세를 받는 시장은 건너뛴다**(T8-03). 실호가 위에 가상 참가자의 주문을 계속
 * 얹으면 그건 실시세도 시뮬도 아니다. 시간으로 어림해 스스로 풀지 않는다 — 보내는 쪽이
 * `MSG_FEED_END`로 끝을 알려야 돌아온다.
 *
 * 유동성 0으로 만든 코어면 생성기가 없으므로 ERR_NOT_SUPPORTED. n이 0 이하면
 * ERR_INVALID_ARG.
 */
int ledger_core_tick(ledger_core_t *core, int32_t n);

/*
 * 바깥에서 받은 실호가를 그 시장 호가창에 심는다(T8-03).
 *
 * ===========================================================================
 * 무엇을 갈아끼우나
 * ===========================================================================
 *
 * **원장 사용자의 미체결 주문은 건드리지 않는다.** 그 밖의 호가(미리 넣어 둔 유동성,
 * 지난 스냅샷이 심어 둔 호가)만 스냅샷의 잔량에 맞춘다. 사용자 주문인지는 주문 매핑에
 * 그 물리 번호가 있는지로 가른다 — 체결 정산이 쓰는 것과 같은 판정이다.
 *
 * ===========================================================================
 * 왜 통째로 지우고 다시 넣지 않나 — 큐 위치
 * ===========================================================================
 *
 * 한 가격의 호가를 전부 지웠다가 새로 넣으면 **내 주문이 그 가격의 맨 앞에 선다.**
 * 호가창은 도착 순서로 시간 우선을 정하는데, 다시 넣은 호가가 내 주문보다 뒤에
 * 도착한 것이 되기 때문이다. 그러면 체결률이 실제보다 부풀고, 이 프로젝트가 재현하려는
 * 것이 정확히 그 큐 우선순위다.
 *
 * 그래서 **차이만 맞춘다.**
 *  - 상대 잔량이 목표보다 많으면 **앞에서부터** 걷는다(수량 감소 정정은 제자리를 지킨다).
 *    실제 장에서도 내 앞의 줄이 먼저 빠진다
 *  - 모자라면 그만큼 새로 넣는다. 새 호가는 큐 뒤, 곧 **내 주문 뒤**에 붙는다
 *
 * ===========================================================================
 * 순서
 * ===========================================================================
 *
 * **줄이는 일을 전부 끝낸 뒤에 넣는다.** 지난 스냅샷의 묵은 호가를 남겨 둔 채 새 호가를
 * 넣으면 둘이 교차해서 있지도 않은 체결이 난다.
 *
 * 넣는 호가가 내 미체결과 교차하면 그대로 체결된다 — 매칭 엔진이 판정한다. 가격이
 * 제한폭 밖이거나 호가 단위에 안 맞으면 그 단은 조용히 버린다(바깥 시세를 내 규칙으로
 * 되받을 수는 없다).
 *
 * 시각은 스냅샷이 들고 온 것을 쓴다. 시스템 시각을 읽지 않는다 — 같은 파일을 재생하면
 * 같은 결과가 나와야 한다(T8-06).
 *
 * `flags`에 `MSG_FEED_END`가 서면 **호가창은 그대로 두고 가상 참가자만 돌려보낸다.**
 * 마지막 실호가를 지우면 시뮬로 돌아간 화면이 텅 빈 호가창을 잠깐 보게 된다.
 *
 * 모르는 시장이면 ERR_INVALID_ARG, 다루지 않는 종목이면 ERR_NOT_FOUND.
 */
int ledger_core_apply_feed(ledger_core_t *core, const msg_book_feed_t *feed);

/* 시장의 호가창. 없는 시장이면 NULL. 테스트와 호가 조회(T6-04)가 쓴다. */
const order_book_t *ledger_core_book(const ledger_core_t *core, market_t market);

/*
 * 계좌를 하나 더 열고 입금한다(T7-01). 데모 계좌 말고 다른 계좌가 필요할 때 — 지금은 "남의
 * 주문은 취소할 수 없다"를 시험하는 데 쓴다. 계좌 자리는 4개다.
 * 이미 있는 계좌면 ERR_DUPLICATE, 자리가 없으면 ERR_POOL_EXHAUSTED.
 */
int ledger_core_open_account(ledger_core_t *core, const char *account,
                             int64_t cash);

/* 계좌의 예수금·묶인 금액. 없는 계좌면 ERR_NOT_FOUND. */
/* 이 원장이 다루는 종목의 호가 단위 표. 채널계가 화면에 통화를 표시하는 데 쓴다. */
tick_table_t ledger_core_tick_table(const ledger_core_t *core);

int ledger_core_balance(ledger_core_t *core, const char *account,
                        int64_t *out_cash, int64_t *out_reserved);

#endif /* MINI_SOR_LEDGER_CORE_H */
