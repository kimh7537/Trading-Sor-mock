#ifndef MINI_SOR_SHM_SEGMENT_H
#define MINI_SOR_SHM_SEGMENT_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/*
 * 워커가 함께 쓰는 공유 메모리 세그먼트.
 *
 * ===========================================================================
 * 어떤 방식으로 잡는가 (완료 조건이 요구한 문서화)
 * ===========================================================================
 *
 * **익명 `mmap(MAP_SHARED | MAP_ANONYMOUS)`를 쓴다. 이름을 붙이지 않는다.**
 *
 * 후보가 셋이었다.
 *
 *  1. **System V `shmget`** — 세그먼트가 **재부팅까지 살아남는다.** 프로세스가
 *     비정상 종료하면 `ipcs`로 찾아 손으로 지워야 하고, 그러지 않으면 커널의
 *     세그먼트 한도를 야금야금 먹는다. 키 충돌도 직접 관리해야 한다
 *
 *  2. **POSIX `shm_open` + `mmap`** — `/dev/shm`에 파일로 보이므로 **워커가 아닌
 *     별도 프로세스도 붙을 수 있다.** 대신 이름 충돌을 관리해야 하고, 죽은 뒤
 *     남은 `/dev/shm` 찌꺼기를 치워야 한다. 테스트를 연달아 돌리면 특히 성가시다
 *
 *  3. **익명 `mmap`** — 채택
 *
 * 3을 고른 이유는 **이 세그먼트를 함께 쓰는 것이 fork한 자손뿐**이기 때문이다.
 * 워커 풀(T3-04)은 부모가 만든 매핑을 자식이 그대로 물려받는다. 이름이 필요한
 * 쪽은 "혈연 관계가 없는 프로세스"인데, 이 구조에는 그런 프로세스가 없다.
 * 아키텍처상 다른 계층(FEP·채널계)은 **전문으로만** 통신하므로 원장의 메모리를
 * 들여다볼 일이 없다.
 *
 * 이름을 없애면 통째로 사라지는 실패가 있다 — 남은 찌꺼기, 이름 충돌, 정리 누락.
 * 프로세스가 전부 죽으면 커널이 매핑을 회수한다. 그것이 유일한 정리 절차다.
 *
 * 나중에 외부 프로세스가 붙어야 한다면 `shm_open`으로 바꾸면 되고, 그 변경은
 * 이 파일 안에서 끝난다 — 바깥은 핸들과 오프셋만 본다.
 *
 * ===========================================================================
 * 초기화는 fork 전에 끝난다
 * ===========================================================================
 *
 * 부모가 세그먼트를 만들고 **다 채운 뒤에** 워커를 fork한다. 그래서 "누가 먼저
 * 초기화하는가"라는 경합이 **아예 생기지 않는다.**
 *
 * 이름 있는 세그먼트를 서로 독립인 프로세스들이 여는 구조였다면, 먼저 연 쪽이
 * 초기화하고 나머지는 기다리는 이중 검사와 잠금이 필요했다. 그 코드는 틀리기
 * 쉽고 시험하기는 더 어렵다. fork 전 초기화는 그 문제를 **설계로** 없앤다.
 *
 * ===========================================================================
 * 포인터를 저장하지 않는다
 * ===========================================================================
 *
 * 세그먼트 안에는 **오프셋만** 둔다. 포인터를 넣어 두면 그 주소가 유효한 것은
 * 그 매핑을 가진 프로세스에서뿐이다. 지금은 fork 상속이라 주소가 같지만,
 * 그 사실에 기대는 순간 "매핑 방식을 바꾸면 조용히 깨지는 코드"가 된다.
 *
 * 부수 효과가 하나 더 있다 — 세그먼트를 바이트로 덤프하면 **그 자체로 해석
 * 가능하다.** 전 구간 통합(T3-15)에서 원장 상태를 들여다볼 때 이 성질이 쓰인다.
 *
 * ===========================================================================
 * 배치
 * ===========================================================================
 *
 *   오프셋              내용
 *   ------------------  ------------------------------------------------
 *   0                   shm_header_t
 *   header->rec_off[0]  영역 0 레코드 배열 (캐시라인 정렬)
 *   header->rec_off[1]  영역 1 레코드 배열 (캐시라인 정렬)
 *
 * **영역을 캐시라인 경계에 맞춘다.** 서로 다른 워커가 각자의 레코드를 만지는데
 * 두 레코드가 같은 캐시라인에 걸치면, 논리적으로는 겹치지 않는 쓰기가 캐시
 * 무효화를 서로 유발한다(거짓 공유). 레코드 크기도 캐시라인 배수로 올린다.
 */

/* "MSSM" — 이 세그먼트가 우리 것인지 본다. */
#define SHM_MAGIC 0x4D53534Du
#define SHM_VERSION 1u

/* x86-64·ARM64 모두 64바이트다. 틀려도 넉넉한 쪽이라 손해가 없다. */
#define SHM_CACHELINE 64u

/* 영역 수. 지금은 계좌(0)와 주문(1) 둘이다. */
#define SHM_REGION_COUNT 2
#define SHM_REGION_ACCOUNT 0
#define SHM_REGION_ORDER 1

/*
 * 세그먼트 크기 상한 (256MB).
 *
 * 없으면 잘못된 인자 하나가 수 GB를 요청해 기계를 멈춘다. 계좌 수만 개 규모의
 * 원장이라 이 한도에 닿을 일이 없다.
 */
#define SHM_SIZE_MAX ((uint64_t)256 * 1024 * 1024)

/*
 * 세그먼트 머리말. **여기에도 포인터는 없다.**
 *
 * 필드 순서와 크기를 고정한다 — 세그먼트를 덤프해서 읽는 것이 이 계층의
 * 디버깅 수단이다.
 */
typedef struct {
    uint32_t magic;
    uint32_t version;
    uint64_t total_size;

    int32_t  rec_count[SHM_REGION_COUNT]; /* 영역별 레코드 수 */
    uint32_t rec_size[SHM_REGION_COUNT];  /* 캐시라인 배수로 올린 크기 */
    uint64_t rec_off[SHM_REGION_COUNT];   /* 세그먼트 시작에서의 오프셋 */

    /*
     * 초기화가 끝났음을 표시한다. fork 전에 부모가 세운다 —
     * 자식은 이 값이 서 있는 세그먼트만 본다.
     */
    uint32_t initialized;
    uint32_t reserved;
} shm_header_t;

typedef struct shm_segment shm_segment_t;

/*
 * 세그먼트를 만들고 초기화한다. **fork 전에 부른다.**
 *
 * 영역마다 레코드 수와 레코드 크기를 받는다. 레코드의 내용은 여기서 모른다 —
 * 계좌 구조는 T3-06의 것이고, 세그먼트는 자리만 내준다.
 *
 * 인자가 잘못됐거나 크기가 한도를 넘거나 매핑에 실패하면 NULL.
 */
shm_segment_t *shm_create(const int32_t rec_count[SHM_REGION_COUNT],
                          const size_t rec_size[SHM_REGION_COUNT]);

/*
 * 매핑을 푼다. **자식에서도 불러야 한다** — 각 프로세스가 제 매핑을 갖는다.
 */
void shm_destroy(shm_segment_t *seg);

/* 머리말. 읽기 전용으로 본다. 없으면 NULL. */
const shm_header_t *shm_header(const shm_segment_t *seg);

/* 세그먼트 전체 크기. 없으면 0. */
uint64_t shm_size(const shm_segment_t *seg);

/*
 * 영역의 레코드 하나를 가리킨다. 범위를 벗어나면 NULL.
 *
 * **포인터를 돌려주되 저장하지 말 것.** 세그먼트 안에 넣어야 한다면 인덱스를
 * 넣는다 — 그것이 이 파일이 지키려는 규칙이다.
 */
void *shm_record(shm_segment_t *seg, int32_t region, int32_t index);

/* 영역의 첫 레코드. 범위를 벗어나면 NULL. */
void *shm_region_base(shm_segment_t *seg, int32_t region);

/*
 * 머리말이 우리 형식인지 본다. magic·version·크기·오프셋을 모두 검사한다.
 * 성공하면 ERR_OK.
 */
int shm_validate(const shm_segment_t *seg);

#endif /* MINI_SOR_SHM_SEGMENT_H */
