#ifndef MINI_SOR_WORKER_POOL_H
#define MINI_SOR_WORKER_POOL_H

#include <stdbool.h>
#include <stdint.h>
#include <sys/types.h>

#include "listener.h"

/*
 * 사전 fork 워커 풀.
 *
 * ===========================================================================
 * 워커가 소켓을 어떻게 나눠 갖는가 (완료 조건이 요구한 문서화)
 * ===========================================================================
 *
 * **fork 전에 리스닝 소켓을 열고, 워커가 그것을 상속받아 각자 `accept()`한다.**
 *
 * 후보가 셋이었다.
 *
 *  1. **부모가 accept하고 fd를 전달한다** (`SCM_RIGHTS`)
 *     부하 분배를 부모가 정하므로 "어느 워커가 얼마나 받았는가"를 부모가 안다.
 *     대신 유닉스 도메인 소켓 한 쌍, 제어 메시지 조립, 전달 실패 처리가 붙는다.
 *     그리고 **부모가 모든 접속의 길목이 된다** — 사전 fork로 없애려던 병목이
 *     모양만 바꿔 돌아온다
 *
 *  2. **공유 리스닝 소켓에서 워커가 각자 accept한다** — 채택
 *
 *  3. **`SO_REUSEPORT`로 워커마다 제 소켓을 갖는다**
 *     커널이 4-튜플 해시로 나눠 주므로 분배가 고르고, 워커를 하나씩 교체하는
 *     무중단 재시작에 유리하다. 대신 **연결이 특정 워커에 묶인다** — 그 워커가
 *     죽으면 그 소켓 큐에 쌓여 있던 접속이 함께 사라진다. 그리고 분배가 커널
 *     해시라 편중이 생겨도 관측할 방법이 마땅치 않다
 *
 * 2를 고른 이유는 **thundering herd가 이 구조에서는 문제가 아니기 때문이다.**
 * 여러 프로세스가 같은 소켓에서 `accept()`를 기다릴 때 리눅스 커널은 대기 큐에서
 * **하나만 깨운다**(exclusive wakeup). 흔히 말하는 herd는 `select`/`epoll`로
 * 리스닝 fd를 감시할 때 생기는 것이고, 여기서는 `accept()`를 직접 부른다.
 *
 * 그래서 가장 적은 코드로 같은 결과를 얻는다. 접속은 손이 빈 워커에게 가고,
 * 워커가 죽어도 남은 워커가 그대로 받는다 — 큐는 소켓에 하나뿐이라 함께
 * 사라지는 접속이 없다.
 *
 * ===========================================================================
 * 워커가 죽으면 다시 띄운다
 * ===========================================================================
 *
 * 워커 하나가 죽는 것은 사고지만 서비스가 멈추는 사고여서는 안 된다. 부모는
 * 자식을 거두면서(`waitpid`) 빈 자리를 채운다. **부모는 전문을 처리하지 않는다** —
 * 감시만 한다. 그래야 부모가 막힐 일이 없다.
 *
 * ===========================================================================
 * 처리 건수 보고
 * ===========================================================================
 *
 * 워커마다 파이프를 하나씩 둔다. 워커는 접속을 하나 끝낼 때마다 1바이트를 쓰고,
 * 부모는 거둘 때 그 파이프를 끝까지 읽어 바이트 수를 센다.
 *
 * 공유 메모리를 쓰지 않는 이유: 그것은 T3-05의 주제이고, 여기서 미리 만들면
 * 그 태스크가 이미 굳은 구조를 물려받는다. 파이프는 **커널이 원자성을 보장하는
 * 1바이트 쓰기**라 락도 필요 없다.
 */

/* 워커 수 상한. 넘게 요청하면 만들지 않는다. */
#define POOL_WORKERS_MAX 64

typedef struct {
    int32_t          worker_count;
    listener_t      *ln; /* 풀이 소유하지 않는다. 호출부가 열고 닫는다 */
    frame_handler_fn fn;
    void            *ctx;
} pool_config_t;

typedef struct worker_pool worker_pool_t;

/*
 * 워커를 미리 만든다. **요청이 오기 전에 fork한다.**
 *
 * 인자가 잘못되거나 fork에 실패하면 NULL. 일부만 만들어진 채로 돌려주지 않는다 —
 * 실패하면 이미 만든 워커를 거두고 NULL을 준다.
 */
worker_pool_t *pool_start(const pool_config_t *cfg);

/*
 * 워커를 감시한다. 죽은 워커가 있으면 다시 띄운다.
 *
 * `listener_request_stop()`이 불릴 때까지 돌고, 그때 돌아온다.
 * 다시 띄운 횟수를 반환한다.
 *
 * **부모는 여기서 전문을 처리하지 않는다.** 감시만 한다.
 */
int pool_supervise(worker_pool_t *pool);

/*
 * 워커 전체에 SIGTERM을 보내고 **전부 거둔다.** 좀비를 남기지 않는다.
 * 거둔 뒤 워커별 처리 건수를 읽어 들인다.
 */
void pool_stop(worker_pool_t *pool);

/* 풀을 해제한다. pool_stop을 먼저 부르지 않았으면 여기서 부른다. */
void pool_destroy(worker_pool_t *pool);

/* 워커 수. NULL이면 0. */
int32_t pool_worker_count(const worker_pool_t *pool);

/*
 * 그 워커가 처리한 접속 수. `pool_stop()` 뒤에 읽는다.
 * 범위를 벗어나면 -1.
 */
int32_t pool_handled(const worker_pool_t *pool, int32_t index);

/* 모든 워커의 처리 건수 합. */
int32_t pool_handled_total(const worker_pool_t *pool);

/* 다시 띄운 횟수. */
int32_t pool_restarts(const worker_pool_t *pool);

/* 그 워커의 pid. 테스트가 워커를 죽여 보기 위해 쓴다. 범위 밖이면 -1. */
pid_t pool_worker_pid(const worker_pool_t *pool, int32_t index);

#endif /* MINI_SOR_WORKER_POOL_H */
